DBMS_UNIT1 = """# DBMS - Unit 1: Relational Model and SQL

## Relational model
Data is stored in relations (tables) of tuples (rows) and attributes
(columns). A super key uniquely identifies a tuple; a candidate key is a
minimal super key; the primary key is the candidate key chosen by the
designer. A foreign key references the primary key of another relation and
enforces referential integrity.

## Relational algebra
Selection (sigma) filters rows, projection (pi) picks columns, join combines
relations on a condition, plus union, set difference and Cartesian product.

## SQL
DDL: CREATE, ALTER, DROP. DML: SELECT, INSERT, UPDATE, DELETE.
`GROUP BY` groups rows for aggregates like COUNT, SUM and AVG; `HAVING`
filters groups, while `WHERE` filters rows before grouping.
An INNER JOIN returns only matching rows; a LEFT OUTER JOIN also returns
unmatched rows from the left table with NULLs on the right.
"""

DBMS_UNIT2 = """# DBMS - Unit 2: Functional Dependencies and Normalization

A functional dependency X -> Y means rows that agree on X agree on Y.
Armstrong's axioms: reflexivity, augmentation and transitivity.

## Normal forms
1NF: every attribute holds atomic values.
2NF: 1NF and no partial dependency of a non-prime attribute on part of a
candidate key.
3NF: 2NF and no transitive dependency of a non-prime attribute on a key.
BCNF: for every non-trivial FD X -> Y, X is a super key. Every BCNF relation
is in 3NF but not every 3NF relation is in BCNF.

## Decomposition
A good decomposition is lossless-join (the original relation can be rebuilt
by joining the parts) and ideally dependency preserving.
"""

DBMS_UNIT3 = """# DBMS - Unit 3: Transactions and Concurrency Control

## ACID
Atomicity (all or nothing), Consistency, Isolation and Durability.

## Schedules
A schedule is conflict serializable if it is conflict-equivalent to some
serial schedule; test it with a precedence graph (serializable iff acyclic).

## Locking
Two-phase locking (2PL) has a growing phase and a shrinking phase and
guarantees conflict serializability. Strict 2PL holds exclusive locks until
commit, avoiding cascading rollbacks.

## Recovery
Write-ahead logging: the log record must reach stable storage before the
data page it describes. Checkpoints bound how much log must be replayed.
"""

