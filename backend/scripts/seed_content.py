OS_UNIT1 = """# Operating Systems - Unit 1: Processes and Threads

## What is a process
A process is a program in execution. It has a program counter, a stack, a
data section and a heap. The operating system represents each process with a
Process Control Block (PCB) holding its state, registers, scheduling
information, memory-management information and open files.

## Process states
A process moves between five states: new, ready, running, waiting (blocked)
and terminated. A running process goes to waiting when it requests I/O, and
back to ready when the I/O completes. The short-term scheduler picks which
ready process runs next.

## Context switch
Switching the CPU from one process to another requires saving the state of
the old process into its PCB and loading the saved state of the new one. The
time spent is pure overhead: no useful work is done while switching. Typical
context-switch times are a few microseconds.

## Process creation
On UNIX, `fork()` creates a child process that is a copy of the parent;
`exec()` replaces the child's memory image with a new program. The parent
can call `wait()` to collect the child's exit status. A child whose parent
has not yet called wait() after it terminated is a zombie; a child whose
parent terminated first is an orphan and is adopted by init (PID 1).

## Threads
A thread is the basic unit of CPU utilisation. Threads of one process share
its code, data and open files but each has its own stack, registers and
program counter. Benefits: responsiveness, resource sharing, economy (cheaper
to create than processes) and scalability on multicore CPUs.
Multithreading models: many-to-one, one-to-one (Linux, Windows) and
many-to-many.

## Inter-process communication
Processes cooperate through shared memory or message passing. Shared memory
is faster after setup but needs synchronisation; message passing is easier
to get right and works across machines. Pipes are a simple unidirectional
message-passing channel between related processes.
"""

OS_UNIT2_V1 = """# Operating Systems - Unit 2: CPU Scheduling

## Criteria
CPU utilisation, throughput, turnaround time, waiting time and response time.

## First-Come, First-Served (FCFS)
Processes run in arrival order. Simple, but suffers from the convoy effect:
short processes wait behind one long process.

## Shortest Job First (SJF)
Runs the process with the shortest next CPU burst. Optimal for average
waiting time, but the next burst length must be predicted.
"""

OS_UNIT2_V2 = OS_UNIT2_V1 + """
## Round Robin (RR)
Each process gets a time quantum (for example 10-100 ms). If it hasn't
finished when the quantum expires it goes to the back of the ready queue.
A very large quantum degenerates to FCFS; a very small one causes too many
context switches.
"""

OS_UNIT2_V3 = OS_UNIT2_V2 + """
## Priority scheduling
Each process has a priority and the highest-priority ready process runs.
Low-priority processes can starve; aging (gradually raising the priority of
waiting processes) fixes starvation.

## Multilevel queue and multilevel feedback queue
Multilevel queue scheduling keeps separate queues (e.g. foreground and
background) with their own algorithms. A multilevel feedback queue lets
processes move between queues based on how they use the CPU, favouring
interactive, I/O-bound processes.

## Worked example
Processes P1 (burst 24), P2 (burst 3), P3 (burst 3) arriving at time 0.
FCFS order P1, P2, P3 gives waiting times 0, 24, 27: average 17.
SJF order P2, P3, P1 gives waiting times 0, 3, 6: average 3.
Round Robin with quantum 4 gives an average waiting time of 5.66.

(Revised: added priority, multilevel queues and the worked example.)
"""

OS_UNIT3 = """# Operating Systems - Unit 3: Memory Management

## Address binding
Logical addresses generated by the CPU are mapped to physical addresses by
the Memory Management Unit (MMU), using a relocation (base) register.

## Contiguous allocation
Memory is divided into partitions. Placement strategies: first fit, best fit
and worst fit. External fragmentation is free memory split into pieces too
small to use; compaction can fix it but is expensive.

## Paging
Physical memory is divided into fixed-size frames and logical memory into
pages of the same size. A page table maps page numbers to frame numbers.
Paging removes external fragmentation but has internal fragmentation in the
last page. A Translation Lookaside Buffer (TLB) caches recent translations;
effective access time = hit ratio x (TLB + memory) + miss ratio x (TLB + 2 x memory).

## Segmentation
Memory is divided into variable-size segments matching the program's logical
structure (code, stack, heap). Each address is (segment number, offset).

## Virtual memory and page replacement
Demand paging loads a page only when it is first referenced; a reference to
a page not in memory causes a page fault. Replacement algorithms: FIFO,
Optimal (replace the page not used for the longest time in future) and LRU
(least recently used). Belady's anomaly: with FIFO, more frames can cause
more page faults. Thrashing happens when a process spends more time paging
than executing, usually because it has fewer frames than its working set.
"""

OS_UNIT4 = """# Operating Systems - Unit 4: Deadlocks

## Necessary conditions (Coffman)
Mutual exclusion, hold and wait, no preemption and circular wait. All four
must hold at the same time for a deadlock to occur.

## Handling deadlocks
Prevention breaks one of the four conditions. Avoidance (Banker's algorithm)
grants a request only if the system stays in a safe state. Detection lets
deadlocks happen and then finds them with a wait-for graph. Recovery aborts
processes or preempts resources.

## Banker's algorithm
Uses Available, Max, Allocation and Need = Max - Allocation matrices. A state
is safe if there is a sequence in which every process can finish using the
available resources plus those released by processes earlier in the sequence.
"""

